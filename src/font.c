Font sys_font;

void font_init(void) {
    memset(&sys_font, 0, sizeof sys_font);
    sys_font.w = FONT_W;
    sys_font.h = FONT_H;
    for (int c = 0; c < NGLYPHS; c++) {
        const char *p = glyphs[c];
        int row = 1, col = 0;            /* the cell's row 0 is the space above */
        for (; *p && row < FONT_H; p++) {
            if (*p == ' ') { row++; col = 0; continue; }
            if (*p == '#') sys_font.g[c][row] |= 1u << col;
            col++;
        }
    }
}
