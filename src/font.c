uint8_t font[128][FONT_H];

void font_init(void) {
    memset(font, 0, sizeof font);
    for (int c = 32; c < 128; c++) {
        const char *p = glyphs[c - 32];
        int row = 1, col = 0;
        for (; *p && row < FONT_H; p++) {
            if (*p == ' ') { row++; col = 0; continue; }
            if (*p == '#') font[c][row] |= (uint8_t)(0x10 >> col);
            col++;
        }
    }
}
